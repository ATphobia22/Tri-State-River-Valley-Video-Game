import sys,unittest
from pathlib import Path
root=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(root/'tools'))
import stage_character_candidate as candidate

class ImportedCharacterTest(unittest.TestCase):
 def test_existing_player_rig_is_staging_eligible_but_never_auto_production_approved(self):
  src=root/'assets/models/river_explorer_rigged.glb'
  if not src.is_file():self.skipTest('Character generated by game build stage')
  result=candidate.assess(src)
  self.assertTrue(result['stagingEligible'],result['blockers'])
  self.assertEqual(result['sourceJointCount'],27)
  self.assertEqual(len(result['sourceActionClips']),13)
  self.assertFalse(result['productionReplacementApproved'])
  self.assertFalse(result['manualDeformationReviewComplete'])
 def test_static_or_missing_asset_never_promotes(self):
  import tempfile
  with tempfile.TemporaryDirectory() as p:
   f=Path(p)/'fake.glb';f.write_bytes(b'glTF'+b'\\x00'*12)
   with self.assertRaises(ValueError):candidate.assess(f)
if __name__=='__main__':unittest.main()
